const CHINESE_LANGUAGE_NAMES = (() => {
  try {
    return typeof Intl.DisplayNames === 'function'
      ? new Intl.DisplayNames(['zh-CN'], { type: 'language' })
      : null;
  } catch {
    return null;
  }
})();

const CHINESE_LANGUAGE_NAME_OVERRIDES: Record<string, string> = {
  bo: '藏语',
  ba: '巴什基尔语',
};

function getLanguageDisplayName(language: Language): string {
  if (language.code === 'auto') return '自动检测（保留原语言）';
  if (language.code === 'auto-translate') return '自动检测（翻译为英语）';
  if (CHINESE_LANGUAGE_NAME_OVERRIDES[language.code]) {
    return CHINESE_LANGUAGE_NAME_OVERRIDES[language.code];
  }

  const localizedName = CHINESE_LANGUAGE_NAMES?.of(language.code);
  return localizedName && localizedName !== language.code ? localizedName : language.name;
}

interface LanguageSelectionProps {
  selectedLanguage: string;
  onLanguageChange: (language: string) => void;
  disabled?: boolean;
  provider?: 'localWhisper' | 'parakeet' | 'deepgram' | 'elevenLabs' | 'groq' | 'openai';
}

export function LanguageSelection({
  selectedLanguage,
  onLanguageChange,
  disabled = false,
  provider = 'localWhisper'
}: LanguageSelectionProps) {
  const [saving, setSaving] = useState(false);
  const { setSelectedLanguage } = useConfig();

  // The bundled Parakeet models do not expose language selection or translation.
  // Keep the persisted Whisper preference untouched so it is restored when the
  // user switches back to Whisper, but never present translation as available.
  const isParakeet = provider === 'parakeet';
  const availableLanguages = isParakeet
    ? LANGUAGES.filter(lang => lang.code === 'auto')
    : LANGUAGES;
  const effectiveSelectedLanguage = isParakeet ? 'auto' : selectedLanguage;

  const handleLanguageChange = async (languageCode: string) => {
    setSaving(true);
    try {
      // Save language preference to localStorage and sync to backend
      setSelectedLanguage(languageCode);
      onLanguageChange(languageCode);
      console.log('Language preference saved:', languageCode);

      // Track language selection analytics
      const selectedLang = LANGUAGES.find(lang => lang.code === languageCode);
      await Analytics.track('language_selected', {
        language_code: languageCode,
        language_name: selectedLang?.name || 'Unknown',
        is_auto_detect: (languageCode === 'auto').toString(),
        is_auto_translate: (languageCode === 'auto-translate').toString()
      });

      // Show success toast
      const languageName = selectedLang
        ? getLanguageDisplayName(selectedLang)
        : languageCode;
      toast.success('转写语言已保存', {
        description: `已设置为${languageName}`
      });
    } catch (error) {
      console.error('Failed to save language preference:', error);
      toast.error('转写语言保存失败', {
        description: '请稍后重试。'
      });
    } finally {
      setSaving(false);
    }
  };

  // Find the selected language name for display
  const selectedLanguageName = LANGUAGES.find(
    lang => lang.code === effectiveSelectedLanguage
  );
  const selectedLanguageDisplayName = selectedLanguageName
    ? getLanguageDisplayName(selectedLanguageName)
    : '自动检测（保留原语言）';

  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between">
        <div className="flex items-center gap-2">
          <Globe className="h-4 w-4 text-gray-600" />
          <h4 className="text-sm font-medium text-gray-900">转写语言</h4>
        </div>
      </div>

      <div className="space-y-2">
        <select
          value={effectiveSelectedLanguage}
          onChange={(e) => handleLanguageChange(e.target.value)}
          disabled={disabled || saving}
          className="w-full px-3 py-2 text-sm bg-white border border-gray-300 rounded-md shadow-sm focus:outline-none focus:ring-1 focus:ring-blue-500 focus:border-blue-500 disabled:bg-gray-50 disabled:text-gray-500"
        >
          {availableLanguages.map((language) => (
            <option key={language.code} value={language.code}>
              {getLanguageDisplayName(language)}
              {language.code !== 'auto' && language.code !== 'auto-translate' && ` (${language.code})`}
            </option>
          ))}
        </select>

        {/* Parakeet language limitation warning */}
        {isParakeet && (
          <div className="p-2 bg-amber-50 border border-amber-200 rounded text-amber-800">
            <p className="font-medium">ℹ️ Parakeet 无法翻译日语</p>
            <p className="mt-1 text-xs">内置 Parakeet 模型不支持日语或翻译。请选择多语言 Whisper 模型进行日语转写或日译英。</p>
          </div>
        )}

        {/* Info text */}
        <div className="text-xs space-y-2 pt-2">
          <p className="text-gray-600">
            <strong>当前：</strong> {selectedLanguageDisplayName}
          </p>
          {effectiveSelectedLanguage === 'auto' && !isParakeet && (
            <div className="p-2 bg-yellow-50 border border-yellow-200 rounded text-yellow-800">
              <p className="font-medium">⚠️ 自动检测可能产生错误结果</p>
              <p className="mt-1">为获得更高准确率，请选择具体语言（如中文、英语或日语）。</p>
            </div>
          )}
          {effectiveSelectedLanguage === 'auto-translate' && (
            <div className="p-2 bg-blue-50 border border-blue-200 rounded text-blue-800">
              <p className="font-medium">🌐 翻译模式已启用</p>
              <p className="mt-1">所有音频都会自动翻译为英语，适合需要英语输出的多语言会议。</p>
            </div>
          )}
          {effectiveSelectedLanguage !== 'auto' && effectiveSelectedLanguage !== 'auto-translate' && (
            <p className="text-gray-600">
              将针对<strong>{selectedLanguageDisplayName}</strong>优化转写
            </p>
          )}
        </div>
      </div>
    </div>
  );
}
